package arc.math;

public class NumberUtils{
    public static int floatToIntBits(float v){ return java.lang.Float.floatToIntBits(v); }
    public static float intToFloat(int v){ return java.lang.Float.intBitsToFloat(v); }
    public static int floatToRawIntBits(float v){ return java.lang.Float.floatToRawIntBits(v); }
}